"""The labelled query photos the eval scores against (US-03).

    make eval-queries   rebuild eval/queries/ photos, labels and credits from selections.csv
    make eval-check     assign dev/test to new photos once, then check the whole set

Photos are stored as `/search` would receive them (D-27); web photos must carry an allowed
licence and a credit (D-26); labels use only the catalogue's words (eval/vocabulary.csv).
"""
import argparse
import hashlib
import io
import sys
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd
from PIL import Image, ImageOps

from vsearch.catalogue import CATALOGUE_TYPES, MANIFEST, RESERVED_TYPES

QUERIES = Path("eval/queries")
VOCABULARY = Path("eval/vocabulary.csv")
CANDIDATES = Path("data/candidates")
KINDS = ("in_catalogue", "out_of_catalogue", "not_fashion")
ALLOWED_LICENSES = {"cc0", "pdm", "by", "by-sa"}  # D-26
ATTRIBUTION_LICENSES = {"by", "by-sa"}  # these require the creator to be credited
LABEL_COLUMNS = ["query_id", "kind", "article_type", "base_colour", "split", "source", "notes"]
SOURCE_COLUMNS = ["query_id", "source", "source_id", "title", "creator", "creator_url", "landing_url",
                  "license", "license_version", "license_url", "changes"]
LONG_SIDE = 640
DEV_SHARE = 0.3
SEED = 2026
MIN_TEST_PER_TYPE = 4
LICENSE_NAMES = {"cc0": "CC0", "pdm": "Public Domain Mark", "by": "CC BY", "by-sa": "CC BY-SA"}


def _read(path, columns):
    if not Path(path).exists():
        return pd.DataFrame(columns=columns)
    return pd.read_csv(path, dtype=str, keep_default_na=False)


def write_vocabulary(manifest=MANIFEST, reserved=RESERVED_TYPES, out=VOCABULARY):
    """US-03: the only words a label may use: catalogue types, reserved types, catalogue colours."""
    cat = pd.read_csv(manifest)
    rows = [{"field": "article_type", "kind": "in_catalogue", "value": t} for t in sorted(cat["article_type"].unique())]
    rows += [{"field": "article_type", "kind": "out_of_catalogue", "value": t} for t in reserved]
    rows += [{"field": "base_colour", "kind": "", "value": c} for c in sorted(cat["base_colour"].unique())]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(out, index=False)


def prepare_image(data, crop=None):
    """D-27: upright, cropped by frame fractions (x0, y0, x1, y1), at most LONG_SIDE px, JPEG, no EXIF."""
    with Image.open(io.BytesIO(data)) as img:
        img = ImageOps.exif_transpose(img).convert("RGB")
    if crop:
        x0, y0, x1, y1 = crop
        w, h = img.size
        img = img.crop((round(x0 * w), round(y0 * h), round(x1 * w), round(y1 * h)))
    img.thumbnail((LONG_SIDE, LONG_SIDE), Image.LANCZOS)  # only ever shrinks
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=90)  # no exif= argument, so none is written
    return buf.getvalue()


def has_exif(path):
    with Image.open(path) as img:
        return bool(img.getexif()) or "exif" in img.info


def assign_splits(labels, seed=SEED, dev_share=DEV_SHARE):
    """US-03 AC3: give dev or test to rows without one; rows that already have a split keep it.
    Stratified by kind, and by article type within in-catalogue photos (D-29), with about dev_share
    of each group in dev but never fewer than MIN_TEST_PER_TYPE in-catalogue test photos per type.
    Order within a group comes from a seeded hash of the query id, not from row order."""
    labels = labels.copy()
    group_key = labels.apply(lambda r: (r["kind"], r["article_type"] if r["kind"] == "in_catalogue" else ""), axis=1)
    for key, rows in labels.groupby(group_key):
        new = rows[~rows["split"].isin(["dev", "test"])]
        if new.empty:
            continue
        have_dev = (rows["split"] == "dev").sum()
        want_dev = round(dev_share * len(rows))
        if key[0] == "in_catalogue":
            want_dev = min(want_dev, max(0, len(rows) - MIN_TEST_PER_TYPE))
        want_dev = max(0, min(len(new), want_dev - have_dev))
        order = sorted(new.index, key=lambda i: hashlib.sha256(f"{seed}:{labels.at[i, 'query_id']}".encode()).hexdigest())
        for n, i in enumerate(order):
            labels.at[i, "split"] = "dev" if n < want_dev else "test"
    return labels


def attribution_text(sources):
    lines = [
        "# Query photo credits",
        "",
        "Generated by `make eval-queries` from `sources.csv`; don't edit. Each photo is used under the "
        "licence shown (D-26). Photos were cropped where noted, resized to 640 px on the long side and "
        "re-encoded as JPEG (D-27); BY-SA adaptations are shared under the same licence.",
        "",
    ]
    for r in sources.sort_values("query_id").itertuples(index=False):
        licence = f"{LICENSE_NAMES.get(r.license, r.license)} {r.license_version}".strip()
        creator = r.creator or "creator not named"
        lines.append(f"- `{r.query_id}`: \"{r.title}\" by {creator} ({r.landing_url}), "
                     f"{licence} ({r.license_url}). Changes: {r.changes}.")
    return "\n".join(lines) + "\n"


@dataclass
class CheckResult:
    errors: list = field(default_factory=list)
    warnings: list = field(default_factory=list)
    counts: dict = field(default_factory=dict)


def check(folder=QUERIES, vocabulary=VOCABULARY):
    """US-03 AC1, AC2, AC4, AC5: every problem with the set, each naming the photo."""
    folder = Path(folder)
    result = CheckResult()
    err = result.errors.append
    labels = _read(folder / "labels.csv", LABEL_COLUMNS)
    sources = _read(folder / "sources.csv", SOURCE_COLUMNS)
    vocab = pd.read_csv(vocabulary, dtype=str, keep_default_na=False)
    in_types = set(vocab.query("field == 'article_type' and kind == 'in_catalogue'")["value"])
    out_types = set(vocab.query("field == 'article_type' and kind == 'out_of_catalogue'")["value"])
    colours = set(vocab.query("field == 'base_colour'")["value"])

    for qid in labels["query_id"][labels["query_id"].duplicated()].unique():
        err(f"{qid}: appears more than once in labels.csv")
    photos = {p.stem for p in folder.glob("*.jpg")}
    for qid in sorted(photos - set(labels["query_id"])):
        err(f"{qid}.jpg: photo has no label row")
    for qid in sorted(photos):
        if has_exif(folder / f"{qid}.jpg"):
            err(f"{qid}.jpg: has EXIF metadata (rebuild it with make eval-queries)")

    for r in labels.itertuples(index=False):
        q = r.query_id
        if q not in photos:
            err(f"{q}: labelled but no photo")
        if r.kind not in KINDS:
            err(f"{q}: kind '{r.kind}' isn't one of {', '.join(KINDS)}")
        elif r.kind == "not_fashion":
            if r.article_type or r.base_colour:
                err(f"{q}: not_fashion photos have no type or colour")
        elif r.kind == "in_catalogue" and r.article_type not in in_types:
            err(f"{q}: '{r.article_type}' isn't a catalogue type")
        elif r.kind == "out_of_catalogue" and r.article_type not in out_types:
            err(f"{q}: '{r.article_type}' isn't a reserved type")
        if r.kind == "in_catalogue" and r.base_colour not in colours:
            err(f"{q}: colour '{r.base_colour}' isn't in the vocabulary")
        if r.kind == "out_of_catalogue" and r.base_colour and r.base_colour not in colours:
            err(f"{q}: colour '{r.base_colour}' isn't in the vocabulary")
        if r.split not in ("dev", "test", ""):
            err(f"{q}: split '{r.split}' isn't dev or test")

    by_id = sources.set_index("query_id") if not sources.empty else pd.DataFrame(columns=SOURCE_COLUMNS[1:])
    for r in labels.itertuples(index=False):
        if r.source.startswith("owner:"):
            continue
        if r.query_id not in by_id.index:
            err(f"{r.query_id}: web photo with no row in sources.csv")
            continue
        s = by_id.loc[r.query_id]
        if s["license"] not in ALLOWED_LICENSES:
            err(f"{r.query_id}: licence '{s['license']}' isn't allowed (D-26: {', '.join(sorted(ALLOWED_LICENSES))})")
        if not s["landing_url"]:
            err(f"{r.query_id}: no source link in sources.csv")
        if not s["creator"] and s["license"] in ATTRIBUTION_LICENSES:
            err(f"{r.query_id}: no creator in sources.csv ({s['license']} requires credit)")
    expected = attribution_text(sources[sources["query_id"].isin(labels["query_id"])])
    attribution = folder / "ATTRIBUTION.md"
    if not attribution.exists() or attribution.read_text() != expected:
        err("ATTRIBUTION.md is out of date: run make eval-queries")

    result.counts["kind"] = labels["kind"].value_counts().to_dict()
    in_cat = labels[labels["kind"] == "in_catalogue"]
    result.counts["type"] = {t: {"dev": int(((in_cat.article_type == t) & (in_cat.split == "dev")).sum()),
                                 "test": int(((in_cat.article_type == t) & (in_cat.split == "test")).sum())}
                             for t in sorted(in_types)}
    for t, n in result.counts["type"].items():
        if n["test"] < MIN_TEST_PER_TYPE:
            result.warnings.append(f"{t} has {n['test']} test photos (fewer than {MIN_TEST_PER_TYPE})")
    return result


def _crop(text):
    return tuple(float(v) for v in text.split()) if text.strip() else None


def build_queries(selections=QUERIES / "selections.csv", candidates=CANDIDATES, out=QUERIES):
    """Turn the labelling record into the stored set: photos, labels.csv, sources.csv, ATTRIBUTION.md.
    Splits already in labels.csv are kept (US-03 AC3)."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    chosen = _read(selections, [])
    cand = _read(Path(candidates) / "candidates.csv", []).set_index("source_id")
    old = _read(out / "labels.csv", LABEL_COLUMNS).set_index("query_id")["split"].to_dict()
    labels, sources = [], []
    for s in chosen.itertuples(index=False):
        c = cand.loc[s.candidate_id]
        crop = _crop(s.crop)
        (out / f"{s.query_id}.jpg").write_bytes(prepare_image((Path(candidates) / f"{s.candidate_id}.jpg").read_bytes(), crop))
        labels.append({"query_id": s.query_id, "kind": s.kind, "article_type": s.article_type,
                       "base_colour": s.base_colour, "split": old.get(s.query_id, ""),
                       "source": "openverse", "notes": s.notes})
        changes = (["cropped to one garment" if crop else None, "resized to 640 px on the long side",
                    "re-encoded as JPEG without metadata"])
        sources.append({"query_id": s.query_id, "source": "openverse", "source_id": s.candidate_id,
                        "title": c["title"], "creator": c["creator"], "creator_url": c["creator_url"],
                        "landing_url": c["landing_url"], "license": c["license"],
                        "license_version": c["license_version"], "license_url": c["license_url"],
                        "changes": "; ".join(x for x in changes if x)})
    for stale in set(p.stem for p in out.glob("*.jpg")) - set(chosen["query_id"]):
        (out / f"{stale}.jpg").unlink()
    labels = pd.DataFrame(labels, columns=LABEL_COLUMNS)
    sources = pd.DataFrame(sources, columns=SOURCE_COLUMNS)
    labels.to_csv(out / "labels.csv", index=False)
    sources.to_csv(out / "sources.csv", index=False)
    (out / "ATTRIBUTION.md").write_text(attribution_text(sources))
    return labels


def main(argv=None):
    parser = argparse.ArgumentParser(description="Build or check the labelled query photos (US-03)")
    parser.add_argument("command", choices=["build", "check", "vocabulary"])
    args = parser.parse_args(argv)
    if args.command == "vocabulary":
        write_vocabulary()
        print(f"Wrote {VOCABULARY}")
        return
    if args.command == "build":
        labels = build_queries()
        print(f"Built {len(labels)} query photos in {QUERIES}/ with labels.csv, sources.csv and ATTRIBUTION.md")
        return
    labels = _read(QUERIES / "labels.csv", LABEL_COLUMNS)
    assigned = assign_splits(labels)
    new = int((labels["split"] != assigned["split"]).sum())
    if new:
        assigned.to_csv(QUERIES / "labels.csv", index=False)
        print(f"Assigned a split to {new} new photos (existing photos keep theirs).")
    result = check()
    print("Photos by kind: " + ", ".join(f"{k} {v}" for k, v in sorted(result.counts["kind"].items())))
    print("In-catalogue photos by type (dev / test):")
    for t, n in result.counts["type"].items():
        print(f"  {t:<14}{n['dev']:>3} / {n['test']:<3}")
    for w in result.warnings:
        print(f"Warning: {w}")
    if result.errors:
        print(f"{len(result.errors)} problems:", *result.errors, sep="\n  ", file=sys.stderr)
        sys.exit(1)
    print("The query set passes every check.")


if __name__ == "__main__":
    main()
